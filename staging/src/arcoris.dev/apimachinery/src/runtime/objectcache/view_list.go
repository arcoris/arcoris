package objectcache

import "arcoris.dev/apimachinery/api/objectstore"

// List returns all latest live items in deterministic view order.
//
// The returned items are detached from v and from the Cache that created v.
func (v View) List() objectstore.ListResult {
	return v.latest.listResult()
}
